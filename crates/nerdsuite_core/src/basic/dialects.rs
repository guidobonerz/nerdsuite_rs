//! The BASIC dialects: their keywords and tokens (the values of VICE petcat), load addresses and
//! output formats, as nerdsuite2's `dialects.js`. The tables below are generated from it.

/// The token of a keyword: one byte, or a prefix and a byte (BASIC 7.0 `$FE xx`, Simons' `$64 xx`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeywordToken {
    Byte(u8),
    Pair(u8, u8),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Keyword {
    pub name: &'static str,
    /// None for the dialects whose output is a text listing.
    pub token: Option<KeywordToken>,
    pub syntax: &'static str,
    pub desc: &'static str,
}

/// What `tokenize` makes of a program.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Output {
    /// A tokenized program with its load address (Commodore).
    Prg,
    /// An ATASCII listing for `ENTER "D:..."` (Atari BASIC, Turbo-Basic XL).
    AtasciiLst,
    /// The ASCII file of `SAVE "x",A` (Locomotive BASIC).
    CpcAscii,
    Trs80Ascii,
    BbcAscii,
    /// A ZX81 `.p` file.
    Zx81P,
}

impl Output {
    /// The name nerdsuite2 gives the format.
    pub fn id(self) -> &'static str {
        match self {
            Output::Prg => "prg",
            Output::AtasciiLst => "atascii-lst",
            Output::CpcAscii => "cpc-ascii",
            Output::Trs80Ascii => "trs80-ascii",
            Output::BbcAscii => "bbc-ascii",
            Output::Zx81P => "zx81-p",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Machine {
    pub id: &'static str,
    pub name: &'static str,
    pub start: Option<u16>,
}

/// How an ASCII listing is written (TRS-80, BBC; the CPC has its own, `listing::CPC`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Listing {
    pub eol: &'static [u8],
    pub end: &'static [u8],
    /// Everything outside strings in capitals, not just the keywords.
    pub upper_all: bool,
    /// `'` starts a remark.
    pub rem_quote: bool,
    pub max_bytes: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Dialect {
    pub id: &'static str,
    pub name: &'static str,
    /// The default machine, one of `machines`.
    pub machine: &'static str,
    /// The default load address.
    pub start: Option<u16>,
    pub output: Output,
    pub machines: &'static [Machine],
    /// The range of line numbers of the listing dialects (0-63999 for the Commodore ones).
    pub min_line: u32,
    pub max_line: u32,
    pub listing: Option<Listing>,
    pub keywords: &'static [Keyword],
}

impl Dialect {
    pub fn machine(&self, id: &str) -> Option<&'static Machine> {
        self.machines.iter().find(|m| m.id == id)
    }
}

/// All dialects, in nerdsuite2's order.
pub fn dialects() -> &'static [Dialect] {
    DIALECTS
}

pub fn dialect(id: &str) -> Option<&'static Dialect> {
    DIALECTS.iter().find(|d| d.id == id)
}

const fn k(token: u8, name: &'static str, syntax: &'static str, desc: &'static str) -> Keyword {
    Keyword {
        name,
        token: Some(KeywordToken::Byte(token)),
        syntax,
        desc,
    }
}

const fn p(
    prefix: u8,
    token: u8,
    name: &'static str,
    syntax: &'static str,
    desc: &'static str,
) -> Keyword {
    Keyword {
        name,
        token: Some(KeywordToken::Pair(prefix, token)),
        syntax,
        desc,
    }
}

const fn w(name: &'static str, syntax: &'static str, desc: &'static str) -> Keyword {
    Keyword {
        name,
        token: None,
        syntax,
        desc,
    }
}

